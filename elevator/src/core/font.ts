function compile(src: Record<string, string>): Map<string, Glyph> {
  const m = new Map<string, Glyph>();
  for (const [ch, s] of Object.entries(src)) {
    const lines = s.split('|');
    const w = Math.max(...lines.map((l) => l.length));
    const rows = lines.map((l) => {
      let v = 0;
      for (let i = 0; i < l.length; i++) if (l[i] === '#') v |= 1 << i;
      return v;
    });
    m.set(ch, { w, rows, h: lines.length });
  }
  return m;
}

export interface Font {
  glyphs: Map<string, Glyph>;
  lineH: number;
  space: number;
  gap: number;
  upper: boolean;
}

export const BIG: Font = { glyphs: compile(BIG_SRC), lineH: 10, space: 3, gap: 1, upper: false };
export const TINY: Font = { glyphs: compile(TINY_SRC), lineH: 6, space: 2, gap: 1, upper: true };

function norm(font: Font, ch: string): string {
  if (ch === '…') return '...';
  if (ch === '’' || ch === '‘') return "'";
  if (ch === '“' || ch === '”') return '"';
  if (ch === '–') return '-';
  return font.upper ? ch.toUpperCase() : ch;
}

export function textWidth(font: Font, text: string, scale = 1): number {
  let w = 0;
  for (const raw of text) {
    for (const ch of norm(font, raw)) {
      if (ch === ' ') { w += font.space; continue; }
      const g = font.glyphs.get(ch) ?? font.glyphs.get('?');
      w += (g ? g.w : 3) + font.gap;
    }
  }
  return Math.max(0, w - font.gap) * scale;
}

/** Draws text with integer pixels. Returns the width drawn. */
export function drawText(
  ctx: CanvasRenderingContext2D, font: Font, text: string, x: number, y: number, color: string, scale = 1,
): number {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const raw of text) {
    for (const ch of norm(font, raw)) {
      if (ch === ' ') { cx += font.space * scale; continue; }
      const g = font.glyphs.get(ch) ?? font.glyphs.get('?');
      if (!g) continue;
      for (let r = 0; r < g.h; r++) {
        const row = g.rows[r];
        if (!row) continue;
        let c = 0;
        while (c < g.w) {
          if (row & (1 << c)) {
            let run = 1;
            while (c + run < g.w && row & (1 << (c + run))) run++;
            ctx.fillRect(cx + c * scale, cy + r * scale, run * scale, scale);
            c += run;
          } else c++;
        }
      }
      cx += (g.w + font.gap) * scale;
    }
  }
  return cx - x;
}

export function drawTextShadow(
  ctx: CanvasRenderingContext2D, font: Font, text: string, x: number, y: number, color: string, shadow: string, scale = 1,
): void {
  drawText(ctx, font, text, x + scale, y + scale, shadow, scale);
  drawText(ctx, font, text, x, y, color, scale);
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D, font: Font, text: string, cx: number, y: number, color: string, scale = 1, shadow?: string,
): void {
  const w = textWidth(font, text, scale);
  const x = Math.round(cx - w / 2);
  if (shadow) drawText(ctx, font, text, x + scale, y + scale, shadow, scale);
  drawText(ctx, font, text, x, y, color, scale);
}

/** Word-wraps text into lines that fit maxW. Honors explicit newlines. */
export function wrap(font: Font, text: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const w of words) {
      const test = line ? line + ' ' + w : w;
      if (textWidth(font, test) > maxW && line) {
        out.push(line);
        line = w;
      } else line = test;
    }
    out.push(line);
  }
  return out;
}
